/**
 * 课表 PDF 解析 —— 内容级测试（Task #9）
 *
 * ============================================================================
 * 为什么要有这个文件
 * ============================================================================
 *
 * `test-pdf-schedule.cjs` 的 108 项全是**结构性自检**：
 *   是否抛异常 / 课名是否为空 / 星期节次是否越界 / 分布是否过度集中。
 *
 * 它挡不住真实错误，实测就漏掉了：
 *   · 三份 PDF 共 10 门课**静默丢失**（表头线误杀）
 *   · 「大学生心理健康教育」详情全空 + 节次错成第 11-11 节
 *   · 教师「雷筱菁式」「王」「黄鹤师」
 *   · `(单)` 单周标记被丢弃
 * 最讽刺的是，那份测试里还把 `黄鹤师` 写成**期望值不变** —— 把 bug 当规格。
 *
 * 本文件反过来：**从真实 PDF 人工摘录期望值，逐条核对星期/节次/课名/教师/
 * 教室/周次/单双周**。任何"读得出来但读错了"的情况都会在这里失败。
 *
 * ============================================================================
 * 期望值是怎么来的（重要：不是从解析结果抄的）
 * ============================================================================
 *
 * 全部来自 `scripts/probe-pdf-fragments.cjs` 打印的**原始文字碎片 + 坐标**，
 * 以及 PDF 内容流里的 `re` 单元格矩形。每条都对应 PDF 里真实存在的文字。
 *
 * 摘录方法（可复现）：
 *   node scripts/probe-pdf-fragments.cjs <pdf> <weekday>
 * 会按 (y 降序, x 升序) 列出该列全部碎片，人工按「课名 + 其下详情」配对。
 *
 * ============================================================================
 * 已知的匹配难点（写在这里供后续维护者理解容差设定）
 * ============================================================================
 *
 * ① **课名与详情在 y 上交叉**。同一列里两个单元格的文字会交错：
 *
 *      陈亚楠 周2:
 *        y=318.5  国家安全教育★        ← 课名 A
 *        y=316.0  组织学与胚胎学★      ← 课名 B
 *        y=306.5  (11-12节)11-12周     ← A 的详情
 *        y=304.0  (7-8节)3-5周,9-11周  ← B 的详情
 *
 *    含义：**按顺序一对一配对**（第 1 个课名 ↔ 第 1 个详情），
 *    而不是「向上找最近的课名」—— 后者会把两个详情都配给 B。
 *
 * ② **表头线不是正文边界**。第一行课程块整体画在「星期一..星期日」之上：
 *
 *      高毅 周4:
 *        y=527.5  国家安全教育★
 *        y=521.0  (星期一..星期日 表头)
 *        y=515.5  (11-12节)11-13周(单)
 *
 * ③ **节次锚点的 y 不可用**。实测三份 PDF 的锚点 y 与节次号不单调：
 *      郭亦菲 {"6":566,"7":551,"1":506,...,"12":44,"5":28}
 *    按 y 从上到下是 6,7,1,2,8,3,9,4,10,11,12,5 —— 完全不是课表顺序。
 *    所以节次**只能**信详情里的 `(N-M节)`。
 *
 * 用法：node scripts/test-pdf-schedule-content.cjs
 */

