let passed = 0;
const failures = [];

function check(desc, ok, got) {
  if (ok) {
    passed += 1;
  } else {
    failures.push(`${desc}　实际=${JSON.stringify(got)}`);
  }
}

/** 把一条课程拍成查找用的键：星期 + 起节 + 止节 + 课名 */
function keyOf(c) {
  return `${c.weekday}|${c.startSection}|${c.endSection}|${c.courseName}`;
}

